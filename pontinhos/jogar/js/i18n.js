  // pt-* cai no português; o resto casa pelo prefixo (pt-PT, en-GB, es-419, hi-IN, in-ID…).
  // Quem não bate com nada vai para o inglês, não para o português.
  function detect() {
    let saved = null;
    try { saved = localStorage.getItem('pt_lang'); } catch (e) {}
    if (saved && STR[saved]) return saved;
    const tags = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || '']);
    for (const tag of tags) {
      const low = String(tag).toLowerCase();
      if (low.indexOf('pt') === 0) return 'pt-BR';
      // 'in' é o código antigo de indonésio que alguns Android ainda mandam
      const base = low.split('-')[0] === 'in' ? 'id' : low.split('-')[0];
      if (STR[base]) return base;
    }
    return FALLBACK;
  }

  let lang = detect();

  function t(key, vars) {
    let s = STR[lang][key];
    if (s === undefined) s = STR[FALLBACK][key];
    if (s === undefined) return key;          // chave nova sem tradução: aparece crua, dá para achar
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : vars[k]));
  }

  const animals = () => ANIMALS[lang] || ANIMALS[FALLBACK];
  const adjs = () => ADJS[lang] || ADJS[FALLBACK];
  const nick = (a, b) => (NICK_FMT[lang] || NICK_FMT[FALLBACK])
    .replace('{a}', animals()[a % animals().length])
    .replace('{b}', adjs()[b % adjs().length]);

  // Percorre o HTML uma vez no boot. `data-i18n` troca o texto, `data-i18n-html` aceita
  // marcação (só usamos <br>), e `data-i18n-aria` traduz o aria-label.
  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
    scope.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
    document.documentElement.lang = lang;
  }

  // Troca o idioma e avisa quem guarda texto montado por JS (o apelido do online, o HUD).
  // Só faz sentido chamar fora de partida — quem escuta remonta o que for preciso.
  function setLang(l) {
    if (!STR[l] || l === lang) return;
    lang = l;
    try { localStorage.setItem('pt_lang', l); } catch (e) {}
    apply();
    document.dispatchEvent(new CustomEvent('langchange', { detail: l }));
  }

  return { t, apply, setLang, animals, adjs, nick, name: l => LANG_NAMES[l] || l,
           get lang() { return lang; }, LANGS: Object.keys(STR) };
